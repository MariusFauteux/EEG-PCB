def put(ref, x, y, rot=0, force=False):
    """Fixed placement (connectors, ICs). force=True allows a courtyard outside the board (edge connectors)."""
    orient(ref, rot); b = box_at(ref, x, y)
    hits = [r for r, o in placed.items() if overlap(b, o)]
    if not force:
        assert legal(ref, b), f'{ref} fixed placement at ({x}, {y}) box {[round(v, 2) for v in b]} is not legal (overlaps {hits})'
    else:
        assert not hits, f'{ref} fixed placement box {[round(v, 2) for v in b]} overlaps {hits}'
    commit(ref, x, y)

def spiral(ref, x0, y0, region=None, rmax=14.0, step=0.25):
    """Nearest legal position to (x0, y0), searched on a 0.25 mm grid outward to rmax, inside region if given."""
    best = None
    n = int(rmax / step)
    cand = sorted(((i * step) ** 2 + (j * step) ** 2, i, j) for i in range(-n, n + 1) for j in range(-n, n + 1) if (i * i + j * j) * step * step <= rmax * rmax)
    for _, i, j in cand:
        x, y = x0 + i * step, y0 + j * step; b = box_at(ref, x, y)
        if region and not inside(b, region):
            continue
        if legal(ref, b):
            return x, y
    return best
FALLBACK = []
def place_near_point(ref, x0, y0, rots=(0, 90, 180, 270), region=None, anchor_pad=None, rmax=14.0):
    """Try each rotation, pick the legal position closest to the target; ties go to the rotation that puts the pad
    sharing anchor_pad's net nearest to that pad."""
    best = None
    for rot in rots:
        orient(ref, rot)
        p = spiral(ref, x0, y0, region, rmax)
        if p is None:
            continue
        d = math.hypot(p[0] - x0, p[1] - y0)
        if anchor_pad is not None:
            FP[ref].SetPosition(V(*p))
            mine = [q for q in FP[ref].Pads() if q.GetNetname() == anchor_pad.GetNetname()]
            if mine:
                d += 0.5 * min(math.dist(L(q.GetPosition()), L(anchor_pad.GetPosition())) for q in mine)
        if best is None or d < best[0] - 1e-9:
            best = (d, rot, p)
    if best is None:
        if region is not None or rmax < 30:          # fall back: any legal spot within 30 mm, recorded in the report
            FALLBACK.append(ref)
            return place_near_point(ref, x0, y0, rots, None, anchor_pad, 30.0)
        raise SystemExit(f'placement failed for {ref} near ({x0:.1f}, {y0:.1f})')
    orient(ref, best[1]); commit(ref, *best[2])

