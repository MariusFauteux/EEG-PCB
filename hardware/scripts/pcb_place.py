def box_at(ref, x, y):
    a = CRT[ref]; return (x + a[0], y + a[1], x + a[2], y + a[3])
def overlap(a, b, gap=0.05):
    return not (a[2] + gap <= b[0] or b[2] + gap <= a[0] or a[3] + gap <= b[1] or b[3] + gap <= a[1])
def inside(a, r): return a[0] >= r[0] and a[1] >= r[1] and a[2] <= r[2] and a[3] <= r[3]
def legal(ref, b, edge=True):
    if edge and not inside(b, (0.3, 0.3, W - 0.3, H - 0.3)):
        return False
    if ref not in ISO_PARTS and ref != 'U600' and overlap(b, ISO_OUT, 0.0):
        return False
    if LARGE.match(ref) and overlap(b, ANT_ZONE, 0.0) and ref != 'U300':
        return False
    return not any(overlap(b, o, 0.15) for r, o in placed.items() if r != ref)   # 0.15 mm keeps neighbouring silk outlines apart

