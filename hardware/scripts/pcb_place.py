def near_pad(ref, anchor, num, out=1.6, region=None, rmax=14.0):
    """Place ref just outside anchor's pad num, on the side the pad faces (decoupling 'at the pin')."""
    p = pad(anchor, num); px, py = L(p.GetPosition()); cx, cy = L(FP[anchor].GetPosition())
